function databaseSeed() {
  const workspace = fullWorkspace();
  const source = workspace.dataSources.find((entry) => entry.id === "ds-full");
  source.properties.push(
    createProperty({ id: "tags", name: "标签", type: "multi_select", options: [{ id: "fe", name: "前端", color: "blue" }, { id: "be", name: "后端", color: "purple" }] }),
    createProperty({ id: "priority", name: "优先级", type: "select", options: [{ id: "p0", name: "P0", color: "red" }, { id: "p1", name: "P1", color: "orange" }] }),
    createProperty({ id: "budget", name: "预算", type: "number", config: { numberFormat: { format: "cny" } } }),
    createProperty({ id: "launch", name: "发布日期", type: "date" }),
    createProperty({ id: "site", name: "网址", type: "url" }),
    createProperty({ id: "note", name: "备注", type: "text" }),
  );
  const original = workspace.databaseItems.find((item) => item.id === "i-3");
  Object.assign(original.values, { tags: ["fe", "be"], priority: "p0", budget: 5000, launch: { start: "2026-09-10", end: null, includeTime: false, timeZone: null } });
  for (const [number, title, score, budget] of [[5, "项目丙", 4, 1200], [6, "项目丁", 1, 300.5], [7, "项目戊", 2, null]]) {
    workspace.databaseItems.push({ id: `i-${number}`, sourceId: "ds-full", pageId: `p-rec-${number}`, parentItemId: null, values: { title, score, budget }, createdAt: FIXTURE_TIME, updatedAt: FIXTURE_TIME });
    workspace.pages.push({ id: `p-rec-${number}`, folderId: "f-z", title, icon: "📄", iconColor: null, cover: null, settings: { fontFamily: "default", smallText: false, fullWidth: false, presentationMode: "default", locked: false }, trashedAt: null, summary: "", contentRevision: 0, summarySourceRevision: 0, summaryUpdatedAt: FIXTURE_TIME, tags: [], sortIndex: 10 + number, createdAt: FIXTURE_TIME, updatedAt: FIXTURE_TIME, databaseSourceId: "ds-full", content: [{ id: `b-rec-${number}`, type: "paragraph", content: `${title}正文` }] });
  }
  workspace.databaseViews.find((view) => view.id === "v-full-table").visiblePropertyIds = null;
  workspace.ui.preferences = { theme: "system", style: "mobai" };
  workspace.ui.expandedFolderIds = workspace.folders.map((folder) => folder.id);
  return workspace;
}

