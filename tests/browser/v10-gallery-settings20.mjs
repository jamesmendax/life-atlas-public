import { mkdirSync } from 'node:fs';
import { browserScenario } from './harness.mjs';
import { coreParityWorkspace } from '../fixtures/core-parity-workspace.mjs';
import { createDatabaseView, createProperty } from '../../src/domain/database.js';
import { normalizeLoadedWorkspace } from '../../src/persistence/normalize.js';
const run = process.env.V10_GALLERY20_RUN || 'red01';
const dir = `.qa/LOCAL-NOTION-001/v10-gallery-settings20/${run}`;
mkdirSync(dir, { recursive: true });
const value = coreParityWorkspace();
value.ui.preferences = { style: 'mobai', theme: 'system' };
value.ui.selectedPageId = 'database-page';
value.pages.find(p => p.id === 'database-page').databaseViewId = 'view-gallery';
value.pages.find(p => p.id === 'alpha-page').cover = { kind: 'gallery', value: 'hokusai-landscape', position: 0 };
const view = value.databaseViews.find(v => v.id === 'view-gallery');
view.config = { ...view.config, openRecordsIn: 'peek', unknown20: { keep: true }, gallery: { preview: { kind: 'page-content', propertyId: null, unknownPreview: 'keep' }, cardSize: 'medium', imageFit: 'cover', visiblePropertyIds: [], unknownGallery: 'keep' } };
const partner = value.dataSources.find(s => s.id === 'partners');
partner.ownerPageId = 'partners-db';
partner.properties.push(createProperty({ id: 'partner-files', name: '供应附件', type: 'files' }));
value.pages.push({ ...structuredClone(value.pages.find(p => p.id === 'database-page')), id: 'partners-db', title: '供应方数据库', databaseSourceId: 'partners', databaseViewId: 'partner-gallery' });
value.databaseViews.push(createDatabaseView({ id: 'partner-gallery', sourceId: 'partners', type: 'gallery', name: '供应画廊', config: { gallery: { preview: { kind: 'page-content', propertyId: null }, cardSize: 'small', imageFit: 'cover', visiblePropertyIds: [] } } }));
const fixture = normalizeLoadedWorkspace(value, { idFactory: p => `${p}-gallery20` });
await browserScenario(`LOCAL-NOTION-001/v10-gallery-settings20/${run}/controls`, async ({ page, check, assert, screenshot, saved, persisted }) => {
  await page.getByRole('complementary', { name: '主导航' }).locator('[data-node-id="database-page"]').click();
  const before = await saved();
  const db = page.locator('section.database-view[data-source-id="projects"]');
  await db.waitFor();
  await db.getByRole('button', { name: '视图设置', exact: true }).click();
  const panel = page.getByRole('dialog', { name: '视图设置', exact: true });
  await panel.getByRole('button', { name: /^布局/ }).click();
  await check('gallery layout exposes menu rows and a keyboard switch instead of native controls', async () => {
    await screenshot('layout');
    assert.equal(await panel.getByRole('button', { name: '画廊预览', exact: true }).count(), 1);
    assert.equal(await panel.getByRole('button', { name: '画廊卡片大小', exact: true }).count(), 1);
    assert.equal(await panel.getByRole('switch', { name: '适应媒体', exact: true }).count(), 1);
    assert.equal(await panel.locator('.db-visible-properties').count(), 0);
  });
  const choose = async (label, option) => { await panel.getByLabel(label, { exact: true }).click(); await panel.getByRole('menuitemradio', { name: option, exact: true }).click(); };
  await check('keyboard submenu consumes first Escape, restores focus and outside clicks dismiss appropriately', async () => {
    const trigger = panel.getByLabel('画廊预览', { exact: true });
    const initialScroll = await panel.evaluate(el => el.scrollTop);
    await trigger.click();
    assert.equal(await panel.evaluate(el => el.scrollTop), initialScroll);
    assert.equal(await panel.getByRole('menuitemradio', { name: '页面内容' }).getAttribute('aria-checked'), 'true');
    await page.keyboard.press('Home');
    assert.equal(await panel.getByRole('menuitemradio', { name: '无', exact: true }).evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('End');
    assert.equal(await panel.getByRole('menuitemradio', { name: '页面内容', exact: true }).evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('ArrowUp'); await page.keyboard.press('ArrowDown');
    await page.keyboard.press('Escape');
    assert.equal(await trigger.evaluate(el => el === document.activeElement), true);
    assert.equal(await panel.count(), 1);
    await trigger.click();
    await panel.getByLabel('画廊卡片大小', { exact: true }).click();
    assert.equal(await panel.getByRole('menu', { name: '画廊预览' }).count(), 0);
    await page.keyboard.press('Escape'); await page.keyboard.press('Escape');
    assert.equal(await panel.count(), 0);
    await db.getByRole('button', { name: '视图设置', exact: true }).click();
    await panel.getByRole('button', { name: /^布局/ }).click();
    await trigger.click();
    await page.locator('body').click({ position: { x: 2, y: 2 } });
    assert.equal(await panel.count(), 0);
    await db.getByRole('button', { name: '视图设置', exact: true }).click();
    await panel.getByRole('button', { name: /^布局/ }).click();
  });
  await check('open submenu follows viewport resize and anchor scrolling without losing focus or changing other data', async () => {
    await page.setViewportSize({ width: 1440, height: 1040 });
    const original = await persisted(w => w.databaseViews.find(v => v.id === 'view-gallery').config.gallery.preview.kind === 'page-content');
    const trigger = panel.getByRole('button', { name: '画廊预览', exact: true });
    await trigger.click();
    const menu = panel.getByRole('menu', { name: '画廊预览', exact: true });
    const active = panel.getByRole('menuitemradio', { name: '附件属性', exact: true });
    await page.keyboard.press('ArrowUp');
    assert.equal(await active.evaluate(el => el === document.activeElement), true);
    const checkPlacement = async () => {
      await page.waitForFunction(() => {
        const anchor = document.querySelector('button[aria-label="画廊预览"]').getBoundingClientRect();
        const box = document.querySelector('[role="menu"][aria-label="画廊预览"]').getBoundingClientRect();
        const width = Math.min(220, innerWidth - 16);
        const left = Math.max(8, Math.min(anchor.right + 4 + width <= innerWidth - 8 ? anchor.right + 4 : anchor.left - width - 4, innerWidth - width - 8));
        const top = Math.max(8, Math.min(anchor.top, innerHeight - box.height - 8));
        return Math.abs(box.left - left) < 1 && Math.abs(box.top - top) < 1 && box.left >= 0 && box.right <= innerWidth && box.top >= 0 && box.bottom <= innerHeight;
      });
      assert.equal(await active.evaluate(el => el === document.activeElement), true);
      assert.equal(await panel.getByRole('menuitemradio', { name: '页面内容', exact: true }).getAttribute('aria-checked'), 'true');
    };
    await checkPlacement();
    await page.setViewportSize({ width: 700, height: 350 });
    await checkPlacement();
    const beforeScroll = await trigger.boundingBox();
    const scroll = await panel.evaluate(el => { const before = el.scrollTop; el.scrollTop = before > 0 ? 0 : 110; return { before, after: el.scrollTop }; });
    assert.notEqual(scroll.after, scroll.before, 'the parent panel actually scrolled');
    await page.waitForFunction(y => Math.abs(document.querySelector('button[aria-label="画廊预览"]').getBoundingClientRect().top - y) > 1, beforeScroll.y);
    await checkPlacement();
    await page.keyboard.press('Enter');
    assert.equal(await menu.count(), 0);
    const after = await persisted(w => w.databaseViews.find(v => v.id === 'view-gallery').config.gallery.preview.kind === 'files-property');
    const previousView = original.databaseViews.find(v => v.id === 'view-gallery');
    const expected = structuredClone(previousView); expected.config.gallery.preview.kind = 'files-property';
    assert.deepEqual(after.databaseViews.find(v => v.id === 'view-gallery'), expected);
    for (const key of ['pages', 'databaseItems', 'dataSources', 'attachments']) assert.deepEqual(after[key], original[key], key);
    for (const old of original.databaseViews.filter(v => v.id !== 'view-gallery')) assert.deepEqual(after.databaseViews.find(v => v.id === old.id), old);
    assert.equal(await db.getAttribute('data-view-id'), 'view-gallery');
    await choose('画廊预览', '页面内容');
    await persisted(w => w.databaseViews.find(v => v.id === 'view-gallery').config.gallery.preview.kind === 'page-content');
    await page.setViewportSize({ width: 1440, height: 1040 });
  });
  await check('preview, sizes and fit update actual cards while metadata and unrelated domains remain stable', async () => {
    const alpha = db.locator('.db-gallery-card[data-item-id="alpha"]');
    const fit = panel.getByRole('switch', { name: '适应媒体', exact: true });
    await fit.focus(); await page.keyboard.press('Space');
    await persisted(w => w.databaseViews.find(v => v.id === 'view-gallery').config.gallery.imageFit === 'contain');
    await choose('画廊预览', '无');
    assert.equal(await db.locator('.db-gallery-preview').count(), 0);
    assert.equal(await fit.count(), 0);
    assert.equal((await persisted(w => w.databaseViews.find(v => v.id === 'view-gallery').config.gallery.preview.kind === 'none')).databaseViews.find(v => v.id === 'view-gallery').config.gallery.imageFit, 'contain');
    const widths = [];
    for (const [label, size] of [['小','small'], ['中','medium'], ['大','large']]) {
      await choose('画廊卡片大小', label);
      await page.waitForFunction(size => document.querySelector('.db-gallery-view')?.dataset.cardSize === size, size);
      widths.push((await alpha.boundingBox()).width);
    }
    assert.ok(widths[0] < widths[1] && widths[1] < widths[2], JSON.stringify(widths));
    await choose('画廊预览', '页面封面');
    assert.equal(await alpha.locator('.db-gallery-cover').count(), 1);
    assert.equal(await fit.getAttribute('aria-checked'), 'true');
    await alpha.locator('.db-gallery-cover img').evaluate(async image => { await image.decode(); if (!image.naturalWidth) throw new Error('cover did not decode'); });
    assert.equal(await alpha.locator('.db-gallery-cover').evaluate(el => getComputedStyle(el).backgroundSize), 'contain');
    await fit.focus(); await page.keyboard.press('Enter');
    assert.equal(await alpha.locator('.db-gallery-cover').evaluate(el => getComputedStyle(el).backgroundSize), 'cover');
    await alpha.locator('.db-gallery-cover img').evaluate(async image => { await image.decode(); if (!image.naturalWidth) throw new Error('cover did not decode after fit change'); });
    await choose('画廊预览', '页面内容');
    assert.equal(await alpha.locator('.db-gallery-content').count(), 1);
    await choose('画廊预览', '附件属性');
    await choose('画廊附件属性', '附件');
    assert.equal(await alpha.locator('.db-gallery-file').count(), 1);
    const after = await persisted(w => w.databaseViews.find(v => v.id === 'view-gallery').config.gallery.preview.propertyId === 'files');
    const v = after.databaseViews.find(v => v.id === 'view-gallery');
    assert.deepEqual(v.config.gallery.preview, { ...before.databaseViews.find(v => v.id === 'view-gallery').config.gallery.preview, kind: 'files-property', propertyId: 'files' });
    assert.equal(v.config.gallery.unknownGallery, 'keep'); assert.deepEqual(v.config.unknown20, { keep: true });
    for (const key of ['pages','databaseItems','dataSources','attachments']) assert.deepEqual(after[key], before[key], key);
    for (const old of before.databaseViews.filter(v => v.id !== 'view-gallery')) assert.deepEqual(after.databaseViews.find(v => v.id === old.id), old);
  });
  await check('property entry shares title count, Back history and actual cards', async () => {
    const row = panel.getByRole('button', { name: /^卡片属性/ });
    assert.equal(await row.locator('small').innerText(), '1');
    await row.click();
    assert.equal(await panel.getByRole('checkbox', { name: '显示 名称' }).isDisabled(), true);
    await panel.getByRole('checkbox', { name: '显示 金额' }).check();
    assert.equal(await db.locator('.db-gallery-card[data-item-id="alpha"] [data-property-id="amount"]').count(), 1);
    await panel.getByRole('checkbox', { name: '显示 金额' }).uncheck();
    await panel.getByRole('button', { name: '返回上一级' }).click();
    assert.equal(await panel.getByRole('button', { name: /^卡片属性/ }).count(), 1);
    assert.deepEqual((await persisted(w => w.databaseViews.find(v => v.id === 'view-gallery').config.gallery.visiblePropertyIds.length === 0)).databaseViews.find(v => v.id === 'view-gallery').config.gallery.visiblePropertyIds, []);
  });
  await check('narrow light and dark menus stay within viewport and reload preserves view configuration', async () => {
    for (const mode of ['light','dark']) {
      await page.emulateMedia({ colorScheme: mode }); await page.setViewportSize({ width: 700, height: 700 });
      await panel.getByLabel('画廊预览', { exact: true }).click();
      const bounds = await panel.getByRole('menu', { name: '画廊预览' }).boundingBox();
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 700 && bounds.y >= 0 && bounds.y + bounds.height <= 700, JSON.stringify(bounds));
      await screenshot('narrow-' + mode); await page.keyboard.press('Escape');
    }
    const snapshot = await saved();
    await page.keyboard.press('Escape'); await page.reload(); await db.waitFor();
    assert.equal(await db.getAttribute('data-view-id'), 'view-gallery');
    const reloaded = await saved();
    assert.deepEqual(reloaded.databaseViews.find(v => v.id === 'view-gallery'), snapshot.databaseViews.find(v => v.id === 'view-gallery'));
  });
  await check('two source galleries keep choices and file properties isolated', async () => {
    const projectBefore = (await saved()).databaseViews.find(v => v.id === 'view-gallery');
    await page.getByRole('complementary', { name: '主导航' }).locator('[data-node-id="partners-db"]').click();
    const partnerDb = page.locator('section.database-view[data-source-id="partners"]'); await partnerDb.waitFor();
    await partnerDb.getByRole('button', { name: '视图设置', exact: true }).click();
    await panel.getByRole('button', { name: /^布局/ }).click();
    await choose('画廊预览', '附件属性');
    await panel.getByLabel('画廊附件属性', { exact: true }).click();
    assert.equal(await panel.getByRole('menuitemradio', { name: '附件', exact: true }).count(), 0);
    await panel.getByRole('menuitemradio', { name: '供应附件', exact: true }).click();
    await choose('画廊卡片大小', '中');
    const after = await persisted(w => w.databaseViews.find(v => v.id === 'partner-gallery').config.gallery.preview.propertyId === 'partner-files' && w.databaseViews.find(v => v.id === 'partner-gallery').config.gallery.cardSize === 'medium');
    assert.deepEqual(after.databaseViews.find(v => v.id === 'view-gallery'), projectBefore);
    await page.keyboard.press('Escape');
    await page.getByRole('complementary', { name: '主导航' }).locator('[data-node-id="database-page"]').click(); await db.waitFor();
    assert.equal(await db.getAttribute('data-view-id'), 'view-gallery');
  });
  await check('open-record choice uses the existing full page and peek paths', async () => {
    await db.getByRole('button', { name: '视图设置', exact: true }).click();
    await panel.getByRole('button', { name: /^布局/ }).click();
    await choose('打开记录的方式', '完整页面');
    await persisted(w => w.databaseViews.find(v => v.id === 'view-gallery').config.openRecordsIn === 'page');
    await page.keyboard.press('Escape');
    await db.locator('.db-gallery-card[data-item-id="alpha"] .db-gallery-open').click();
    await page.getByLabel('页面标题', { exact: true }).waitFor();
    assert.equal(await page.getByLabel('页面标题', { exact: true }).inputValue(), 'Alpha 项目');
    assert.equal(await page.getByRole('dialog', { name: '记录预览', exact: true }).count(), 0);
    await page.getByRole('complementary', { name: '主导航' }).locator('[data-node-id="database-page"]').click();
    await db.waitFor();
    await db.getByRole('button', { name: '视图设置', exact: true }).click();
    await panel.getByRole('button', { name: /^布局/ }).click();
    await choose('打开记录的方式', '中心预览');
    await persisted(w => w.databaseViews.find(v => v.id === 'view-gallery').config.openRecordsIn === 'peek');
    await page.keyboard.press('Escape');
    await db.locator('.db-gallery-card[data-item-id="alpha"] .db-gallery-open').click();
    const peek = page.getByRole('dialog', { name: '记录预览', exact: true });
    await peek.waitFor();
    assert.equal(await peek.locator('.life-editor').getAttribute('data-page-id'), 'alpha-page');
    await page.keyboard.press('Escape');
  });
}, { workspace: fixture });
