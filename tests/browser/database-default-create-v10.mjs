import { browserScenario } from './harness.mjs';
import { coreParityWorkspace } from '../fixtures/core-parity-workspace.mjs';

const workspace = coreParityWorkspace();
workspace.ui.preferences = { theme: 'system', style: 'mobai' };
workspace.pages.find(page => page.id === 'database-page').databaseViewId = 'view-board';
workspace.databaseViews.find(view => view.id === 'view-board').visiblePropertyIds = [];
workspace.databaseItems.find(item => item.id === 'gamma').values.status = null;
workspace.databaseItems.find(item => item.id === 'gamma').values.title = '新记录';
workspace.pages.find(page => page.id === 'gamma-page').title = '新记录';
delete workspace.databaseItems.find(item => item.id === 'gamma').values.labels;
delete workspace.databaseItems.find(item => item.id === 'gamma').values.people;

await browserScenario('database-default-create-v10', async ({ page, check, assert, saved, persisted }) => {
  await page.getByRole('complementary', { name: '主导航' }).locator('[data-node-id="database-page"]').click();
  const db = page.locator('section.database-view[data-source-id="projects"]');
  await db.waitFor();
  const titleSemantics = (state, itemId) => page.evaluate(async ({ state, itemId }) => {
    const { projectViewItems, resolvePropertyValue } = await import('/src/domain/database.js');
    const source = state.dataSources.find(entry => entry.id === 'projects');
    const item = state.databaseItems.find(entry => entry.id === itemId);
    const formula = { id: 'empty-title-check', type: 'formula', config: { expression: 'empty(prop("名称"))' } };
    const matches = operator => projectViewItems(state, { sourceId: source.id, filter: { propertyId: 'title', operator } }).some(entry => entry.id === itemId);
    return { empty: matches('is_empty'), notEmpty: matches('is_not_empty'), formula: resolvePropertyValue(state, source, item, formula) };
  }, { state, itemId });
  const assertFilter = async (expectedName, shouldMatchEmpty) => {
    await db.getByRole('button', { name: '视图设置', exact: true }).click();
    const settings = page.getByRole('dialog', { name: '视图设置', exact: true });
    await settings.getByRole('button', { name: '筛选', exact: true }).click();
    await settings.getByRole('button', { name: '+ 条件', exact: true }).click();
    await settings.getByLabel('筛选属性 0', { exact: true }).selectOption('title');
    const operator = settings.getByLabel('筛选操作 0', { exact: true });
    await operator.selectOption('is_empty');
    assert.equal(await db.getByRole('button', { name: expectedName, exact: true }).count(), shouldMatchEmpty ? 1 : 0);
    await operator.selectOption('is_not_empty');
    assert.equal(await db.getByRole('button', { name: expectedName, exact: true }).count(), shouldMatchEmpty ? 0 : 1);
    await settings.getByRole('button', { name: '清除筛选', exact: true }).click();
    await settings.getByRole('button', { name: '关闭视图设置', exact: true }).click();
  };
  await check('board New without a name persists one item and page across blur and reload', async () => {
    const before = await saved();
    const group = db.locator('.db-board-column[data-group-key="doing"]');
    await group.getByRole('button', { name: '新建页面', exact: true }).click();
    await group.getByRole('textbox', { name: '页面名称' }).waitFor();
    await page.waitForTimeout(800);
    const clicked = await saved();
    await db.getByRole('button', { name: '视图设置', exact: true }).click();
    await page.waitForTimeout(800);
    const blurred = await saved();
    await page.reload(); await db.waitFor();
    const reloaded = await saved();
    const diff = value => ({ items: value.databaseItems.filter(item => !before.databaseItems.some(old => old.id === item.id)), pages: value.pages.filter(entry => !before.pages.some(old => old.id === entry.id)) });
    const evidence = { clicked: diff(clicked), blurred: diff(blurred), reloaded: diff(reloaded) };
    console.log('CREATION_EVIDENCE', JSON.stringify(evidence));
    for (const state of Object.values(evidence)) {
      assert.equal(state.items.length, 1, 'one database item must persist');
      assert.equal(state.pages.length, 1, 'one page must persist');
      assert.equal(state.items[0].pageId, state.pages[0].id);
      assert.equal(state.items[0].values.status, 'doing');
      assert.equal(state.items[0].values.title, '', 'new item title is an empty business value');
      assert.equal(state.pages[0].title, '', 'new page title is an empty business value');
    }
    assert.equal(evidence.clicked.items[0].id, evidence.reloaded.items[0].id);
    const first = evidence.reloaded.items[0];
    assert.deepEqual(await titleSemantics(reloaded, first.id), { empty: true, notEmpty: false, formula: true });
    await assertFilter('无标题', true);
    await db.locator('.db-board-column[data-group-key="doing"]').getByRole('button', { name: '无标题', exact: true }).click();
    const peek = page.getByRole('dialog', { name: '记录预览' });
    await peek.getByRole('textbox', { name: '记录标题' }).fill('稍后命名');
    const named = await persisted(value => value.databaseItems.find(item => item.id === first.id)?.values.title === '稍后命名');
    assert.equal(named.pages.find(entry => entry.id === first.pageId).title, '稍后命名');
    assert.equal(named.databaseItems.length, before.databaseItems.length + 1);
    assert.equal(named.pages.length, before.pages.length + 1);
    assert.equal(named.databaseItems.find(item => item.id === 'gamma').values.title, '新记录');
    assert.equal(named.pages.find(entry => entry.id === 'gamma-page').title, '新记录');
    await peek.getByRole('button', { name: '关闭预览' }).click();
    assert.deepEqual(await titleSemantics(named, first.id), { empty: false, notEmpty: true, formula: false });
    await assertFilter('稍后命名', false);
  });
  await check('naming the immediately created item keeps its identity and Enter continues naming', async () => {
    const before = await saved();
    const group = db.locator('.db-board-column[data-group-key="doing"]');
    await group.getByRole('button', { name: '新建页面', exact: true }).click();
    const input = group.getByRole('textbox', { name: '页面名称' });
    const created = await persisted(value => value.databaseItems.length === before.databaseItems.length + 1);
    const item = created.databaseItems.find(candidate => !before.databaseItems.some(old => old.id === candidate.id));
    assert.ok(item && created.pages.some(entry => entry.id === item.pageId));
    assert.equal(await group.locator('.db-board-card').count(), (await group.locator('header > small').innerText()) * 1);
    await input.fill('连续命名第一条'); await input.press('Enter');
    const renamed = await persisted(value => value.databaseItems.find(entry => entry.id === item.id)?.values.title === '连续命名第一条');
    assert.equal(renamed.pages.find(entry => entry.id === item.pageId).title, '连续命名第一条');
    assert.equal(renamed.databaseItems.length, before.databaseItems.length + 2);
    assert.equal(await input.isVisible(), true);
    const nextItem = renamed.databaseItems.find(entry => !before.databaseItems.some(old => old.id === entry.id) && entry.id !== item.id);
    assert.ok(nextItem && renamed.pages.some(entry => entry.id === nextItem.pageId));
    await input.fill('连续命名第二条'); await input.press('Enter');
    const second = await persisted(value => value.databaseItems.some(entry => entry.values.title === '连续命名第二条'));
    assert.equal(second.databaseItems.length, before.databaseItems.length + 3);
    assert.equal(second.databaseItems.find(entry => entry.id === nextItem.id).values.title, '连续命名第二条');
    assert.equal(second.databaseItems.find(entry => entry.id === item.id).pageId, item.pageId);
    assert.equal(second.pages.filter(entry => !before.pages.some(old => old.id === entry.id)).length, 3);
  });
  await check('empty Enter retains the first record and creates exactly one next record', async () => {
    const group = db.locator('.db-board-column[data-group-key="todo"]');
    const before = await saved();
    await group.getByRole('button', { name: '新建页面', exact: true }).click();
    const input = group.getByRole('textbox', { name: '页面名称' });
    const clicked = await persisted(value => value.databaseItems.length === before.databaseItems.length + 1);
    const first = clicked.databaseItems.find(entry => !before.databaseItems.some(old => old.id === entry.id));
    await input.press('Enter');
    const after = await persisted(value => value.databaseItems.length === before.databaseItems.length + 2);
    const added = after.databaseItems.filter(entry => !before.databaseItems.some(old => old.id === entry.id));
    assert.equal(added.length, 2);
    assert.ok(added.some(entry => entry.id === first.id && entry.pageId === first.pageId));
    assert.equal(after.pages.filter(entry => !before.pages.some(old => old.id === entry.id)).length, 2);
    assert.ok(added.every(entry => entry.values.status === 'todo' && after.pages.some(page => page.id === entry.pageId)));
    assert.equal(await input.isVisible(), true);
    const latest = added.find(entry => entry.id !== first.id);
    await input.press('Escape');
    const canceled = await persisted(value => Boolean(value.pages.find(entry => entry.id === latest.pageId)?.trashedAt));
    assert.equal(canceled.pages.find(entry => entry.id === first.pageId).trashedAt, null);
    assert.equal(canceled.databaseItems.find(entry => entry.id === latest.id).pageId, latest.pageId);
    assert.equal(canceled.databaseItems.find(entry => entry.id === first.id).pageId, first.pageId);
    assert.equal(await group.locator('header > small').innerText(), String(Number(await group.locator('.db-board-card').count())));
    await page.reload(); await db.waitFor();
    const reloaded = await saved();
    assert.ok(reloaded.pages.find(entry => entry.id === latest.pageId).trashedAt);
    assert.equal(reloaded.pages.find(entry => entry.id === first.pageId).trashedAt, null);
  });
  await check('ungrouped New creates one ungrouped record and page before blur', async () => {
    const group = db.locator('.db-board-column[data-group-key="未分组"]');
    const before = await saved();
    await group.getByRole('button', { name: '新建页面', exact: true }).click();
    const after = await persisted(value => value.databaseItems.length === before.databaseItems.length + 1);
    const item = after.databaseItems.find(entry => !before.databaseItems.some(old => old.id === entry.id));
    assert.equal(item.values.status, null);
    assert.ok(after.pages.some(entry => entry.id === item.pageId));
    await db.getByRole('button', { name: '视图设置', exact: true }).click();
    await page.reload(); await db.waitFor();
    const reloaded = await saved();
    assert.equal(reloaded.databaseItems.find(entry => entry.id === item.id).pageId, item.pageId);
    assert.equal(reloaded.databaseItems.find(entry => entry.id === item.id).values.status, null);
    assert.ok(reloaded.pages.some(entry => entry.id === item.pageId));
  });
  await check('multi-select and people ungrouped New stay visible after blur and reload', async () => {
    const failures = [];
    for (const propertyId of ['labels', 'people']) {
      await db.getByRole('button', { name: '视图设置', exact: true }).click();
      const panel = page.getByRole('dialog', { name: '视图设置', exact: true });
      await panel.getByRole('button', { name: '分组', exact: true }).click();
      await panel.getByLabel('一级分组', { exact: true }).selectOption(propertyId);
      await panel.getByRole('button', { name: '关闭视图设置', exact: true }).click();
      const group = db.locator('.db-board-column[data-group-key="未分组"]');
      const before = await saved();
      const count = await group.locator('.db-board-card').count();
      await group.getByRole('button', { name: '新建页面', exact: true }).click();
      await group.getByRole('textbox', { name: '页面名称' }).waitFor();
      const created = await persisted(value => value.databaseItems.length === before.databaseItems.length + 1);
      const item = created.databaseItems.find(entry => !before.databaseItems.some(old => old.id === entry.id));
      assert.deepEqual(item.values[propertyId], []);
      assert.ok(created.pages.some(entry => entry.id === item.pageId && !entry.trashedAt));
      await db.getByRole('button', { name: '视图设置', exact: true }).click();
      const blurredCount = await group.locator('.db-board-card').count();
      await page.reload(); await db.waitFor();
      const reloaded = await saved();
      const reloadedCount = await group.locator('.db-board-card').count();
      const stored = reloaded.databaseItems.find(entry => entry.id === item.id);
      assert.equal(stored?.pageId, item.pageId);
      assert.deepEqual(stored.values[propertyId], []);
      assert.ok(reloaded.pages.some(entry => entry.id === item.pageId && !entry.trashedAt));
      console.log('EMPTY_ARRAY_GROUP_EVIDENCE', JSON.stringify({ propertyId, itemId: item.id, pageId: item.pageId, baselineCards: count, blurredCount, reloadedCount, storedValue: stored.values[propertyId] }));
      if (blurredCount !== count + 1 || reloadedCount !== count + 1) failures.push(propertyId);
    }
    assert.deepEqual(failures, [], 'new empty-array items must remain visible in the ungrouped column');
  });
}, { workspace });
