import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const sourcePath = path.join(root, "node_modules", "@emoji-mart", "data", "sets", "15", "native.json");
const outputPath = path.join(root, "src", "data", "emojiRegistry.generated.js");

const labels = {
  people: "人物", nature: "自然", foods: "食物", activity: "活动",
  places: "旅行", objects: "物品", symbols: "符号", flags: "旗帜"
};
const zhAliases = {
  grinning: ["笑脸", "开心"], smile: ["微笑", "开心"], joy: ["大笑", "开心"],
  heart: ["爱心", "喜欢"], blue_heart: ["蓝心"], star: ["星星"], sparkles: ["闪光", "灵感"],
  fire: ["火", "热门"], bulb: ["灯泡", "灵感"], brain: ["大脑", "思考"], books: ["书", "阅读"],
  book: ["书", "阅读"], memo: ["笔记", "写作"], pencil2: ["铅笔", "写作"], microscope: ["显微镜", "科学"],
  test_tube: ["试管", "化学"], alembic: ["实验", "化学"], atom_symbol: ["原子", "物理"],
  rocket: ["火箭", "科技"], airplane: ["飞机", "旅行"], compass: ["指南针", "旅行"],
  mountain: ["山", "自然"], evergreen_tree: ["森林", "自然"], ocean: ["海洋", "自然"],
  milky_way: ["银河", "星空"], crescent_moon: ["月亮", "夜晚"], sun_with_face: ["太阳", "天气"],
  trophy: ["奖杯", "成就"], dart: ["目标"], briefcase: ["工作"], computer: ["电脑", "技术"],
  iphone: ["手机", "设备"], camera: ["相机", "摄影"], art: ["绘画", "设计"], musical_note: ["音乐"],
  house: ["家", "主页"], office: ["办公", "工作"], school: ["学校", "学习"], moneybag: ["钱", "财务"],
  chart_with_upwards_trend: ["图表", "增长"], calendar: ["日历", "计划"], alarm_clock: ["时间", "提醒"],
  white_check_mark: ["完成", "确认"], warning: ["警告"], link: ["链接"], pushpin: ["固定", "重要"]
};

const data = JSON.parse(fs.readFileSync(sourcePath, "utf8"));
const seen = new Set();
const registry = [];
for (const category of data.categories ?? []) {
  for (const id of category.emojis ?? []) {
    if (seen.has(id)) continue;
    const item = data.emojis?.[id];
    const native = item?.skins?.[0]?.native;
    if (!native) continue;
    seen.add(id);
    const categoryLabel = labels[category.id] ?? category.id;
    const aliases = zhAliases[id] ?? [];
    const keywords = (item.keywords ?? []).map(String).filter(Boolean).slice(0, 24);
    registry.push({
      id,
      native,
      name: item.name ?? id,
      category: category.id,
      categoryLabel,
      keywords: [...new Set([...keywords, ...aliases])],
      searchText: [id, item.name ?? "", category.id, categoryLabel, ...keywords, ...aliases].join(" ").toLocaleLowerCase()
    });
  }
}
const categories = (data.categories ?? []).map((category) => ({
  id: category.id,
  label: labels[category.id] ?? category.id,
  count: registry.filter((item) => item.category === category.id).length
})).filter((category) => category.count > 0);

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath,
  `// Generated by scripts/generate-emoji-registry.mjs from @emoji-mart/data. Do not edit by hand.\n` +
  `export const emojiRegistry = ${JSON.stringify(registry, null, 2)};\n` +
  `export const emojiCategories = ${JSON.stringify(categories, null, 2)};\n` +
  `export const emojiRegistryMeta = ${JSON.stringify({ count: registry.length, source: "@emoji-mart/data", unicode: "15", license: "MIT" }, null, 2)};\n`
);
console.log(JSON.stringify({ emojis: registry.length, categories: categories.length, output: outputPath }, null, 2));
